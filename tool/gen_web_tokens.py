#!/usr/bin/env python3
"""Generate web-v2/tokens.css from the 'web' sections of design/tokens.json.

Reads only design/tokens.json. The generated file is consumed by web-v2/app.css.
Android's lib/theme/tokens.g.dart is intentionally untouched.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = json.loads((ROOT / 'design' / 'tokens.json').read_text(encoding='utf-8'))
WEB = DATA['web']
COLORS = DATA['colors']['web']


def color_block(name, values):
    lines = [f':root[data-theme="{name}"]{{']
    for key, value in values.items():
        if key == 'note':
            continue
        lines.append(f'  --{key}:{value};')
    lines.append('}')
    return '\n'.join(lines)


def main():
    out = ['/* Generated by tool/gen_web_tokens.py - do not edit by hand. */']
    out.append(color_block('light', COLORS['light']))
    out.append(color_block('dark', COLORS['dark']))
    out.append(':root{')
    r = WEB['radii']
    out.append(f"  --r-card:{r['card']}px;--r-tile:{r['tile']}px;"
               f"--r-pill:{r['pill']}px;--r-control:{r['control']}px;")
    t = WEB['type']
    for key, (size, weight, tracking) in t.items():
        out.append(f'  --t-{key}-size:{size}px;--t-{key}-weight:{weight};'
                   f'--t-{key}-tracking:{tracking}em;')
    s = WEB['shell']
    for key, value in s.items():
        out.append(f'  --shell-{key}:{value}px;')
    m = DATA['motion']
    out.append(f"  --ease:cubic-bezier({','.join(str(x) for x in m['ease'])});")
    out.append('}')
    target = ROOT / 'web-v2' / 'tokens.css'
    target.parent.mkdir(exist_ok=True)
    target.write_text('\n'.join(out) + '\n', encoding='utf-8')
    print(f'wrote {target.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
