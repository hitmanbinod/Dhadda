#!/usr/bin/env python3
"""Generate the web token stylesheet and Dart token constants from tokens.json.

Dependency-free: standard library only. Run from the repo root:
    python3 scripts/sync_tokens.py
    python3 scripts/sync_tokens.py --check   # verify generated files are current
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TOKENS = ROOT / "design" / "tokens.json"
CSS_OUT = ROOT / "design" / "tokens.css"
DART_OUT = ROOT / "lib" / "theme" / "tokens.g.dart"


def rgba(value: str) -> str:
    return value


def css_color(c):
    if isinstance(c, str) and c.startswith("rgba"):
        return c
    return c


def render_css(data):
    lines = [
        "/* Generated by scripts/sync_tokens.py — do not edit by hand. */",
        ":root{",
    ]
    for theme in ("dark", "light"):
        if theme == "light":
            lines.append("}")
            lines.append('[data-theme="light"]{')
        c = data["colors"][theme]
        mapping = {
            "bg": "--bg", "surface": "--surface", "surface2": "--surface-2",
            "hairline": "--hairline", "text": "--text", "text2": "--text-2",
            "text3": "--text-3", "accent": "--accent", "onAccent": "--on-accent",
            "accentTint": "--accent-tint", "expense": "--expense",
            "income": "--income", "warn": "--warn", "lent": "--lent",
            "scrim": "--scrim",
        }
        for key, var in mapping.items():
            lines.append(f"  {var}:{css_color(c[key])};")
    lines.append("}")
    lines.append(":root{")
    r = data["radii"]
    for key, value in r.items():
        lines.append(f"  --r-{key}:{value}px;")
    for i, value in enumerate(data["spacing"], 1):
        lines.append(f"  --s{i}:{value}px;")
    m = data["motion"]
    lines.append("  --ease:cubic-bezier(%s);" % ",".join(str(x) for x in m["ease"]))
    lines.append("  --spring:cubic-bezier(%s);" % ",".join(str(x) for x in m["spring"]))
    for i, value in enumerate(m["durations"], 1):
        lines.append(f"  --d{i}:{value}ms;")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def dart_int(color: str) -> str:
    """Hex or rgba() -> 0xAARRGGBB for Dart's Color."""
    color = color.strip()
    if color.startswith("#"):
        h = color.lstrip("#")
        if len(h) == 6:
            h = "FF" + h
        return f"0x{h.upper()}"
    if color.startswith("rgba"):
        nums = color[color.find("(") + 1:color.find(")")].split(",")
        r, g, b = (int(float(x.strip())) for x in nums[:3])
        a = int(round(float(nums[3].strip()) * 255))
        return f"0x{a:02X}{r:02X}{g:02X}{b:02X}"
    if color.startswith("rgb"):
        nums = color[color.find("(") + 1:color.find(")")].split(",")
        r, g, b = (int(float(x.strip())) for x in nums[:3])
        return f"0xFF{r:02X}{g:02X}{b:02X}"
    raise ValueError(f"unsupported colour: {color}")


def camel(theme: str, key: str) -> str:
    parts = key.replace("2", "Two").replace("3", "Three")
    return theme + parts[0].upper() + parts[1:]


def render_dart(data):
    lines = [
        "// Generated by scripts/sync_tokens.py — do not edit by hand.",
        "import 'dart:ui' show Color;",
        "",
        "/// Quiet Ledger tokens mirrored from design/tokens.json.",
        "abstract final class DesignTokens {",
    ]
    for theme in ("dark", "light"):
        c = data["colors"][theme]
        suffix = "" if theme == "dark" else "Light"
        for key in ("bg", "surface", "surface2", "hairline", "text", "text2",
                    "text3", "accent", "onAccent", "expense", "income", "warn", "lent"):
            lines.append(f"  static const Color {camel(theme, key)} = Color({dart_int(c[key])});")
        lines.append("")
    lines.append("  static const List<Color> category = [")
    for c in data["colors"]["category"]:
        lines.append(f"    Color({dart_int(c)}),")
    lines.append("  ];")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main():
    check = "--check" in sys.argv
    data = json.loads(TOKENS.read_text(encoding="utf-8"))
    outputs = {CSS_OUT: render_css(data), DART_OUT: render_dart(data)}
    if check:
        for path, content in outputs.items():
            existing = path.read_text(encoding="utf-8") if path.exists() else ""
            if existing != content:
                print(f"sync_tokens: STALE {path.relative_to(ROOT)}")
                return 1
        print("sync_tokens: tokens in sync")
        return 0
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"sync_tokens: wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
